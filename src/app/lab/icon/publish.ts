import { writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";
import { type IconConfig, renderIcon } from "@/lib/icon-mark";

export type Marks = Record<"favicon" | "header", IconConfig>;

export const KEEPER_PATH = "src/data/icon-mark.json";
const HEADER_MODULE_PATH = "src/components/rainshift-mark-svg.ts";

const png = (svg: string, size: number) =>
  sharp(Buffer.from(svg), { density: 288 }) // 4× supersample
    .resize(size, size)
    .png()
    .toBuffer();

/** ICO container with PNG-compressed entries. */
function ico(images: { size: number; data: Buffer }[]) {
  const header = Buffer.alloc(6 + 16 * images.length);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(images.length, 4);
  let offset = header.length;
  images.forEach(({ size, data }, i) => {
    const o = 6 + i * 16;
    header.writeUInt8(size, o);
    header.writeUInt8(size, o + 1);
    header.writeUInt16LE(1, o + 4);
    header.writeUInt16LE(32, o + 6);
    header.writeUInt32LE(data.length, o + 8);
    header.writeUInt32LE(offset, o + 12);
    offset += data.length;
  });
  return Buffer.concat([header, ...images.map((i) => i.data)]);
}

/** Writes every production artifact derived from the saved marks. Returns the written paths. */
export async function publishIcons(marks: Marks): Promise<string[]> {
  const written: string[] = [];
  const write = async (file: string, data: string | Buffer) => {
    await writeFile(path.join(process.cwd(), file), data);
    written.push(file);
  };

  await write(KEEPER_PATH, `${JSON.stringify(marks, null, 2)}\n`);

  // Header: pre-rendered so the renderer and artwork never ship to the client.
  // Emitted in Biome's own format so the generated file passes lint.
  const { header } = marks;
  const headerSvg = renderIcon(header, header.displaySize, "header");
  if (/['\\]/.test(headerSvg))
    throw new Error("Header SVG can't be single-quoted");
  await write(
    HEADER_MODULE_PATH,
    `// Generated by /lab/icon from ${KEEPER_PATH}. Do not edit; save in the lab instead.\n` +
      `export const HEADER_SVG =\n  '${headerSvg}';\n` +
      `export const HEADER_GAP = ${header.headerGap};\n`,
  );

  // Tab icons always sit on the tile, or a cream dove vanishes on light tabs.
  const favicon: IconConfig = { ...marks.favicon, tileOn: true };
  const images = await Promise.all(
    [16, 32, 48].map(async (size) => ({
      size,
      data: await png(renderIcon(favicon, size), size),
    })),
  );
  await write("src/app/favicon.ico", ico(images));

  // Home-screen icons have room for the header's rim and beak. Full-bleed
  // without a border: iOS and Android apply their own masks.
  const appIcon: IconConfig = {
    ...favicon,
    tileBorder: 0,
    beakFill: header.beakFill,
    rimWidth: header.rimWidth,
    rimOpacity: header.rimOpacity,
    rimBlur: header.rimBlur,
    rimColor: header.rimColor,
  };
  for (const [file, size] of [
    ["src/app/apple-icon.png", 180],
    ["public/icon-192.png", 192],
    ["public/icon-512.png", 512],
  ] as const) {
    await write(file, await png(renderIcon(appIcon, size), size));
  }

  return written;
}
